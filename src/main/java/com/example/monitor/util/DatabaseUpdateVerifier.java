package com.example.monitor.util;

import lombok.extern.slf4j.Slf4j;

/**
 * 更新系クエリが実際に行を更新できたかを確かめ、1 行も更新できなければ警告する。
 *
 * <h2>なぜ必要か</h2>
 * このアプリの更新はどれも「主キーを指定した UPDATE」なので、<b>該当する行が無くても
 * SQL としては成功し、0 行更新で静かに終わる</b>。戻り値を捨てていると成功と区別できない。
 *
 * <p>実際に起こりうる経路がある。録画完了を記録するのは録画開始時に起動した仮想スレッドだが、
 * その完了を待っている間に利用者が画面から録画履歴を削除すると、
 * <b>更新対象の行はもう存在しない</b>。録画ファイルは完成しているのに記録だけが残らない、
 * という状態になるが、今までは何のログも出なかった。
 *
 * <p>「配信していない」と「判定できなかった」を区別するのと同じ考え方で、
 * <b>「更新した」と「更新できなかった」を混同しない</b>ためのもの。
 *
 * <h2>例外にしない理由</h2>
 * 0 行更新はデータ不整合ではなく、上の例のように<b>正常な操作の結果として起こりうる</b>。
 * ここで例外を投げると巡回や録画の完了処理が巻き添えで止まるため、記録に留める。
 */
@Slf4j
public final class DatabaseUpdateVerifier {

    /** ユーティリティクラスのためインスタンス化させない。 */
    private DatabaseUpdateVerifier() {
    }

    /**
     * 更新件数を確かめ、0 件なら警告として記録する。
     *
     * @param updatedRows 更新系クエリが返した更新件数
     * @param operation   何をしようとしたか（ログに出す説明）
     * @param id          対象の主キー
     */
    public static void verify(int updatedRows, String operation, Object id) {
        if (updatedRows == 0) {
            log.warn("更新対象が見つからず、1件も更新されませんでした: 操作={}, id={}", operation, id);
        }
    }
}
